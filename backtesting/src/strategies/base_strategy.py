"""Base strategy interface for trading strategies.

This module defines the abstract base class that all trading strategies must implement,
providing a standardized interface for signal generation and strategy configuration.
"""

from abc import ABC, abstractmethod
from datetime import datetime, timedelta
from decimal import Decimal
from typing import Dict, List, Optional, Any, Union
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, validator

from ..loaders.data_loader import HistoricalDataPoint


class TechnicalIndicators(BaseModel):
    """Container for technical indicators used in strategy analysis."""
    
    # Moving averages
    sma_5: Optional[float] = None
    sma_10: Optional[float] = None
    sma_20: Optional[float] = None
    sma_50: Optional[float] = None
    ema_12: Optional[float] = None
    ema_26: Optional[float] = None
    
    # Momentum indicators
    rsi: Optional[float] = None
    macd: Optional[float] = None
    macd_signal: Optional[float] = None
    macd_histogram: Optional[float] = None
    
    # Volatility indicators
    bollinger_upper: Optional[float] = None
    bollinger_middle: Optional[float] = None
    bollinger_lower: Optional[float] = None
    atr: Optional[float] = None
    
    # Volume indicators
    volume_sma: Optional[float] = None
    volume_ratio: Optional[float] = None
    
    # Price action
    price_change: Optional[float] = None
    price_change_pct: Optional[float] = None
    volatility: Optional[float] = None
    
    # Custom indicators (strategy-specific)
    custom: Dict[str, Any] = Field(default_factory=dict)


class StrategySignal(BaseModel):
    """Trading signal generated by a strategy."""
    
    id: UUID = Field(default_factory=uuid4)
    timestamp: datetime
    symbol: str
    direction: str  # "UP" or "DOWN"
    confidence: str  # "LOW", "MEDIUM", "HIGH"
    probability: float  # 0.0 to 1.0
    expiry_minutes: int = 60
    
    # Strategy information
    strategy_name: str
    strategy_version: str = "1.0"
    
    # Technical analysis data
    indicators: TechnicalIndicators
    entry_price: Decimal
    
    # Signal reasoning
    signal_reason: str
    conditions_met: List[str] = Field(default_factory=list)
    
    # Risk management
    suggested_bet_size: Optional[Decimal] = None
    risk_level: str = "MEDIUM"  # "LOW", "MEDIUM", "HIGH"
    
    @validator('direction')
    def validate_direction(cls, v):
        if v not in ["UP", "DOWN"]:
            raise ValueError('direction must be "UP" or "DOWN"')
        return v
    
    @validator('confidence')
    def validate_confidence(cls, v):
        if v not in ["LOW", "MEDIUM", "HIGH"]:
            raise ValueError('confidence must be "LOW", "MEDIUM", or "HIGH"')
        return v
    
    @validator('probability')
    def validate_probability(cls, v):
        if not 0.0 <= v <= 1.0:
            raise ValueError('probability must be between 0.0 and 1.0')
        return v
    
    @validator('risk_level')
    def validate_risk_level(cls, v):
        if v not in ["LOW", "MEDIUM", "HIGH"]:
            raise ValueError('risk_level must be "LOW", "MEDIUM", or "HIGH"')
        return v


class StrategyConfig(BaseModel):
    """Base configuration for trading strategies."""
    
    # Strategy identification
    name: str
    version: str = "1.0"
    description: str = ""
    
    # Signal generation parameters
    min_confidence: str = "MEDIUM"
    min_probability: float = 0.6
    contract_duration_minutes: int = 60
    
    # Risk management
    max_risk_per_trade: float = 0.02  # 2% of capital
    max_daily_trades: int = 50
    max_concurrent_trades: int = 5
    
    # Technical analysis parameters
    lookback_periods: int = 50  # Number of historical periods to analyze
    
    # Strategy-specific parameters
    parameters: Dict[str, Any] = Field(default_factory=dict)
    
    @validator('min_confidence')
    def validate_min_confidence(cls, v):
        if v not in ["LOW", "MEDIUM", "HIGH"]:
            raise ValueError('min_confidence must be "LOW", "MEDIUM", or "HIGH"')
        return v
    
    @validator('min_probability')
    def validate_min_probability(cls, v):
        if not 0.0 <= v <= 1.0:
            raise ValueError('min_probability must be between 0.0 and 1.0')
        return v


class BaseStrategy(ABC):
    """Abstract base class for all trading strategies.
    
    All custom strategies must inherit from this class and implement the required methods.
    This ensures a consistent interface for the backtesting engine.
    """
    
    def __init__(self, config: StrategyConfig):
        """Initialize the strategy with configuration.
        
        Args:
            config: Strategy configuration parameters
        """
        self.config = config
        self.name = config.name
        self.version = config.version
        
        # Historical data storage for technical analysis
        self._price_history: List[HistoricalDataPoint] = []
        self._indicators_cache: Dict[str, TechnicalIndicators] = {}
        
        # Strategy state
        self._is_initialized = False
        self._last_signal_time: Optional[datetime] = None
        
        # Performance tracking
        self._signals_generated = 0
        self._successful_signals = 0
    
    @abstractmethod
    async def generate_signal(self, data_point: HistoricalDataPoint) -> Optional[StrategySignal]:
        """Generate a trading signal based on current market data.
        
        This is the core method that each strategy must implement. It should analyze
        the current market data and historical context to determine if a trading
        opportunity exists.
        
        Args:
            data_point: Current market data point
            
        Returns:
            StrategySignal if a trading opportunity is identified, None otherwise
        """
        pass
    
    @abstractmethod
    def calculate_indicators(self, data_point: HistoricalDataPoint) -> TechnicalIndicators:
        """Calculate technical indicators for the current data point.
        
        Args:
            data_point: Current market data point
            
        Returns:
            TechnicalIndicators object with calculated values
        """
        pass
    
    def update_data(self, data_point: HistoricalDataPoint) -> None:
        """Update the strategy with new market data.
        
        Args:
            data_point: New market data point to add to history
        """
        self._price_history.append(data_point)
        
        # Keep only the required lookback periods
        max_history = self.config.lookback_periods * 2  # Keep extra for safety
        if len(self._price_history) > max_history:
            self._price_history = self._price_history[-max_history:]
        
        # Calculate and cache indicators
        indicators = self.calculate_indicators(data_point)
        self._indicators_cache[data_point.timestamp.isoformat()] = indicators
    
    def get_indicators(self, timestamp: Optional[datetime] = None) -> Optional[TechnicalIndicators]:
        """Get technical indicators for a specific timestamp.
        
        Args:
            timestamp: Timestamp to get indicators for. If None, returns latest.
            
        Returns:
            TechnicalIndicators for the specified timestamp, or None if not found
        """
        if timestamp is None and self._price_history:
            timestamp = self._price_history[-1].timestamp
        
        if timestamp:
            return self._indicators_cache.get(timestamp.isoformat())
        return None
    
    def get_price_history(self, periods: Optional[int] = None) -> List[HistoricalDataPoint]:
        """Get historical price data.
        
        Args:
            periods: Number of recent periods to return. If None, returns all.
            
        Returns:
            List of historical data points
        """
        if periods is None:
            return self._price_history.copy()
        return self._price_history[-periods:] if periods > 0 else []
    
    def validate_signal_conditions(self, signal: StrategySignal) -> bool:
        """Validate that a signal meets the strategy's minimum requirements.
        
        Args:
            signal: Signal to validate
            
        Returns:
            True if signal meets requirements, False otherwise
        """
        # Check minimum confidence level
        confidence_levels = ["LOW", "MEDIUM", "HIGH"]
        min_level_idx = confidence_levels.index(self.config.min_confidence)
        signal_level_idx = confidence_levels.index(signal.confidence)
        
        if signal_level_idx < min_level_idx:
            return False
        
        # Check minimum probability
        if signal.probability < self.config.min_probability:
            return False
        
        return True
    
    def calculate_position_size(self, signal: StrategySignal, 
                              available_capital: Decimal) -> Decimal:
        """Calculate appropriate position size for a signal.
        
        Args:
            signal: Trading signal
            available_capital: Available capital for trading
            
        Returns:
            Suggested position size
        """
        # Simple risk-based position sizing
        risk_multiplier = {
            "LOW": 0.5,
            "MEDIUM": 1.0,
            "HIGH": 1.5
        }
        
        base_risk = available_capital * Decimal(str(self.config.max_risk_per_trade))
        multiplier = Decimal(str(risk_multiplier.get(signal.risk_level, 1.0)))
        
        return base_risk * multiplier
    
    def get_strategy_info(self) -> Dict[str, Any]:
        """Get strategy information and statistics.
        
        Returns:
            Dictionary with strategy information
        """
        win_rate = (
            self._successful_signals / self._signals_generated 
            if self._signals_generated > 0 else 0.0
        )
        
        return {
            "name": self.name,
            "version": self.version,
            "description": self.config.description,
            "signals_generated": self._signals_generated,
            "successful_signals": self._successful_signals,
            "win_rate": win_rate,
            "is_initialized": self._is_initialized,
            "last_signal_time": self._last_signal_time,
            "price_history_length": len(self._price_history),
            "config": self.config.dict()
        }
    
    def reset(self) -> None:
        """Reset strategy state for new simulation."""
        self._price_history.clear()
        self._indicators_cache.clear()
        self._is_initialized = False
        self._last_signal_time = None
        self._signals_generated = 0
        self._successful_signals = 0
    
    # Helper methods for common technical analysis calculations
    
    def _calculate_sma(self, periods: int, price_type: str = "close") -> Optional[float]:
        """Calculate Simple Moving Average.
        
        Args:
            periods: Number of periods for SMA
            price_type: Type of price to use ("close", "high", "low", "open")
            
        Returns:
            SMA value or None if insufficient data
        """
        if len(self._price_history) < periods:
            return None
        
        prices = []
        for data_point in self._price_history[-periods:]:
            if price_type == "close":
                prices.append(float(data_point.close_price))
            elif price_type == "high":
                prices.append(float(data_point.high_price))
            elif price_type == "low":
                prices.append(float(data_point.low_price))
            elif price_type == "open":
                prices.append(float(data_point.open_price))
        
        return sum(prices) / len(prices) if prices else None
    
    def _calculate_ema(self, periods: int, price_type: str = "close") -> Optional[float]:
        """Calculate Exponential Moving Average.
        
        Args:
            periods: Number of periods for EMA
            price_type: Type of price to use
            
        Returns:
            EMA value or None if insufficient data
        """
        if len(self._price_history) < periods:
            return None
        
        prices = []
        for data_point in self._price_history[-periods:]:
            if price_type == "close":
                prices.append(float(data_point.close_price))
            elif price_type == "high":
                prices.append(float(data_point.high_price))
            elif price_type == "low":
                prices.append(float(data_point.low_price))
            elif price_type == "open":
                prices.append(float(data_point.open_price))
        
        if not prices:
            return None
        
        # Calculate EMA
        multiplier = 2.0 / (periods + 1)
        ema = prices[0]  # Start with first price
        
        for price in prices[1:]:
            ema = (price * multiplier) + (ema * (1 - multiplier))
        
        return ema
    
    def _calculate_rsi(self, periods: int = 14) -> Optional[float]:
        """Calculate Relative Strength Index.
        
        Args:
            periods: Number of periods for RSI calculation
            
        Returns:
            RSI value or None if insufficient data
        """
        if len(self._price_history) < periods + 1:
            return None
        
        # Get price changes
        price_changes = []
        for i in range(1, len(self._price_history)):
            current_price = float(self._price_history[i].close_price)
            previous_price = float(self._price_history[i-1].close_price)
            price_changes.append(current_price - previous_price)
        
        if len(price_changes) < periods:
            return None
        
        # Calculate gains and losses
        recent_changes = price_changes[-periods:]
        gains = [change for change in recent_changes if change > 0]
        losses = [-change for change in recent_changes if change < 0]
        
        avg_gain = sum(gains) / periods if gains else 0
        avg_loss = sum(losses) / periods if losses else 0
        
        if avg_loss == 0:
            return 100.0
        
        rs = avg_gain / avg_loss
        rsi = 100 - (100 / (1 + rs))
        
        return rsi
    
    def _calculate_volatility(self, periods: int = 20) -> Optional[float]:
        """Calculate price volatility (standard deviation of returns).
        
        Args:
            periods: Number of periods for volatility calculation
            
        Returns:
            Volatility value or None if insufficient data
        """
        if len(self._price_history) < periods + 1:
            return None
        
        # Calculate returns
        returns = []
        for i in range(1, len(self._price_history)):
            current_price = float(self._price_history[i].close_price)
            previous_price = float(self._price_history[i-1].close_price)
            if previous_price > 0:
                returns.append((current_price - previous_price) / previous_price)
        
        if len(returns) < periods:
            return None
        
        recent_returns = returns[-periods:]
        mean_return = sum(recent_returns) / len(recent_returns)
        
        variance = sum((r - mean_return) ** 2 for r in recent_returns) / len(recent_returns)
        volatility = variance ** 0.5
        
        return volatility